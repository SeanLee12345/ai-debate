CREATE DATABASE IF NOT EXISTS ai_debate;
USE ai_debate;

CREATE TABLE IF NOT EXISTS Users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  side VARCHAR(30) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'offline',
  win INT NOT NULL DEFAULT 0,
  trophy INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS chat_history (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(100) NOT NULL,
  my_id VARCHAR(100) NOT NULL,
  mate_id VARCHAR(100) NOT NULL,
  my_message TEXT NOT NULL,
  ai_answer TEXT,
  register_pot TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
